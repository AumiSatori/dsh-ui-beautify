import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const require=createRequire(join(dirname(fileURLToPath(import.meta.url)),'../../package.json'))
const {chromium}=require('playwright')
const [html,output]=process.argv.slice(2)
if(!html||!output)throw Error('Usage: node check-shell.mjs <built.html> <output-dir>')
await mkdir(resolve(output),{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[],requests=[],checks=[]
page.on('pageerror',e=>errors.push(String(e)))
page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url())})
async function shot(name){await page.screenshot({path:join(resolve(output),name+'.png')})}
async function settled(){await page.waitForFunction(()=>Math.abs(window.particlePreview.snapshot().progress-window.particlePreview.snapshot().target/100)<.002);await page.waitForTimeout(300)}
async function bounds(){
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  for(const selector of ['#composer','#occupancy','#demo','#import-svg']){
    const b=await page.locator(selector).boundingBox()
    assert.ok(b.x>=0&&b.x+b.width<=page.viewportSize().width+1&&b.y+b.height<=page.viewportSize().height,selector+' fits viewport')
  }
  const composer=await page.locator('#composer').boundingBox(),controls=await page.locator('.controls').boundingBox()
  assert.ok(composer.y+composer.height<controls.y,'composer and controls do not overlap')
  const status=await page.locator('.control-status').boundingBox()
  assert.ok(status.y+status.height<=controls.y+controls.height,'status fits controls')
}
try{
  await page.goto(pathToFileURL(resolve(html)).href)
  await page.waitForFunction(()=>window.particlePreview?.snapshot().ready)
  await settled();await bounds()
  assert.equal(await page.locator('body').getAttribute('data-view'),'chat')
  assert.equal(await page.locator('select,input[type=range],input[type=checkbox],input[type=radio]').count(),0)
  await shot('deepseek-black-82')
  await page.locator('[data-progress="20"]').click();await settled();await shot('deepseek-black-20')
  await page.locator('[data-progress="100"]').click();await settled();await shot('deepseek-black-100')
  await page.locator('[data-theme-choice=light]').click();await page.waitForTimeout(800);await shot('deepseek-white-100')
  assert.equal(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgb(255, 255, 255)')
  assert.equal(await page.locator('[data-theme-choice=light]').getAttribute('aria-pressed'),'true')
  await page.locator('[data-progress="40"]').click();await settled();await shot('deepseek-white-40')
  checks.push('desktop black/white themes and continuous density')
  await page.locator('.thinking').click();await page.waitForTimeout(100)
  const mid=await page.locator('.thinking-detail').evaluate(e=>({height:e.getBoundingClientRect().height,filter:getComputedStyle(e).filter}))
  await shot('thinking-middle')
  await page.waitForTimeout(300)
  const full=await page.locator('.thinking-detail').evaluate(e=>e.getBoundingClientRect().height)
  assert.ok(mid.height>0&&mid.height<full,'expansion has a real intermediate height')
  assert.notEqual(mid.filter,'none')
  await page.locator('.thinking').click();await page.waitForTimeout(100)
  const collapse=await page.locator('.thinking-detail').evaluate(e=>e.getBoundingClientRect().height)
  assert.ok(collapse>0&&collapse<full,'collapse animates actual height')
  await page.waitForTimeout(300)
  assert.equal(await page.locator('.thinking-detail').evaluate(e=>e.getBoundingClientRect().height),0)
  checks.push('thinking expansion/collapse intermediate heights and blur')
  await page.locator('#sidebar-close').click();await page.waitForTimeout(350)
  assert.equal(await page.locator('.sidebar').evaluate(e=>e.inert),true)
  await bounds();await page.locator('#sidebar-open').click();await page.waitForTimeout(350)
  await page.locator('[data-chat=svg]').click();await page.waitForTimeout(500)
  assert.match(await page.locator('.message-user').innerText(),/SVG/)
  await page.locator('#new-chat').click();await page.waitForTimeout(500)
  assert.equal(await page.locator('.welcome').count(),1)
  await page.locator('#message-input').fill('这是本地模拟的一轮对话')
  await page.locator('#deep-think').click()
  assert.equal(await page.locator('#deep-think').getAttribute('aria-pressed'),'true')
  await page.locator('#message-input').press('Enter');await page.waitForTimeout(500)
  assert.equal(await page.locator('.message-user').last().textContent(),'这是本地模拟的一轮对话')
  assert.equal(await page.locator('#message-input').inputValue(),'')
  checks.push('sidebar toggle, history, new chat, local message and input options')
  await page.locator('[data-chat=memory]').click();await page.waitForTimeout(500)
  for(const [width,height] of [[1000,800],[760,932],[430,932],[390,844]]){
    await page.setViewportSize({width,height});await page.waitForTimeout(700);await bounds()
    await shot('white-'+width)
  }
  await page.locator('[data-theme-choice=dark]').click();await page.waitForTimeout(800);await shot('black-390')
  await page.locator('#sidebar-open').click();await page.waitForTimeout(350)
  assert.equal(await page.locator('.sidebar').evaluate(e=>e.inert),false)
  await shot('mobile-sidebar')
  await page.locator('#sidebar-scrim').click({position:{x:320,y:200}});await page.waitForTimeout(350)
  assert.equal(await page.locator('.sidebar').evaluate(e=>e.inert),true)
  checks.push('responsive 1000/760/430/390 widths; mobile sidebar scrim')
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(pathToFileURL(resolve(html)).href+'?theme=light')
  await page.waitForFunction(()=>window.particlePreview?.snapshot().ready)
  await settled()
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
  assert.equal(await page.locator('[data-theme-choice=light]').getAttribute('aria-pressed'),'true')
  await shot('deepseek-white-direct')
  checks.push('direct white-theme URL initializes theme and particles together')
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[])
  await writeFile(join(resolve(output),'shell-verification.json'),JSON.stringify({checks,errors,requests},null,2))
  console.log(JSON.stringify({checks,errors,requests},null,2))
}finally{await browser.close()}
