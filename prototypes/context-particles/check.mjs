import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '../../package.json'))
const { chromium } = require('playwright')
const [html, output] = process.argv.slice(2)
if (!html || !output) throw new Error('Usage: node check.mjs <built.html> <output-dir>')
await mkdir(resolve(output), { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = [], requests = [], samples = []
page.on('pageerror', e => errors.push(String(e)))
page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()) })
const snapshot = () => page.evaluate(() => window.particlePreview.snapshot())
async function settle(target) {
  await page.waitForFunction(p => Math.abs(window.particlePreview.snapshot().progress - p / 100) < .002, target)
  await page.waitForTimeout(160)
}
try {
  await page.goto(pathToFileURL(resolve(html)).href)
  await page.waitForFunction(() => window.particlePreview?.snapshot().ready)
  await settle(80)
  assert.equal((await snapshot()).mode, 'WebGL2')
  assert.equal(await page.locator('select,input[type=range],input[type=checkbox],input[type=radio]').count(), 0)
  await page.screenshot({ path: join(resolve(output), 'deepseek-dark.png') })
  await page.locator('[data-view="art"][type=button]').click()
  await page.waitForTimeout(1100)
  for (const p of [0, 20, 40, 60, 80, 100]) {
    await page.locator(`[data-progress="${p}"]`).click()
    await settle(p)
    const sample = await snapshot()
    samples.push(sample)
    await page.screenshot({ path: join(resolve(output), `dark-${p}.png`) })
    console.log(`PASS ${p}%: ${sample.visible} particles; ${sample.mode}; ${sample.fps} FPS`)
  }
  assert.ok(samples.every((s, i) => !i || s.visible > samples[i - 1].visible), 'particle count increases with occupancy')
  await page.locator('#theme').click()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: join(resolve(output), 'light-100.png') })
  await page.locator('[data-view="chat"][type=button]').click()
  await page.waitForTimeout(1100)
  await page.screenshot({ path: join(resolve(output), 'light-chat.png') })
  await page.locator('#theme').click()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: join(resolve(output), 'dark-chat.png') })
  await page.locator('#occupancy').focus()
  await page.keyboard.press('Home')
  assert.equal((await snapshot()).target, 0)
  await page.keyboard.press('End')
  assert.equal((await snapshot()).target, 100)
  await page.keyboard.press('ArrowLeft')
  assert.equal((await snapshot()).target, 99)
  const slider = await page.locator('#occupancy').boundingBox()
  await page.mouse.move(slider.x + slider.width * .25, slider.y + 15)
  await page.mouse.down()
  await page.mouse.move(slider.x + slider.width * .75, slider.y + 15, { steps: 6 })
  await page.mouse.up()
  assert.ok(Math.abs((await snapshot()).target - 75) < 1)
  await page.locator('#compress').click()
  await settle(22)
  assert.equal((await snapshot()).target, 22)
  console.log('PASS slider: mouse drag, keyboard, compaction')
  await page.locator('[data-quality=high]').click()
  await page.waitForTimeout(1600)
  assert.ok((await snapshot()).budget > 9900)
  await page.locator('#demo').click()
  const start = (await snapshot()).target
  await page.waitForTimeout(1300)
  assert.ok((await snapshot()).target > start + 5)
  await page.locator('#demo').click()
  await page.waitForTimeout(1800)
  await page.locator('#pause').click()
  await page.waitForTimeout(400)
  const before = (await snapshot()).frames
  await page.waitForTimeout(350)
  assert.equal((await snapshot()).frames, before, 'pause stops drawing after settling')
  await page.locator('#pause').click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.locator('[data-progress="80"]').click()
  await page.waitForTimeout(300)
  const reduced = await snapshot()
  await page.waitForTimeout(350)
  assert.equal((await snapshot()).frames, reduced.frames, 'reduced motion has no ongoing draw loop')
  assert.ok(Math.abs(reduced.progress - .80) < 1e-9)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.locator('[data-view="art"][type=button]').click()
  await page.setViewportSize({ width: 430, height: 932 })
  await page.waitForTimeout(1000)
  await page.screenshot({ path: join(resolve(output), 'mobile.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  for (const selector of ['#demo', '#compress', '#pause', '#occupancy']) {
    const box = await page.locator(selector).boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= 431 && box.y + box.height < 932)
  }
  console.log('PASS quality, automatic demo, pause, reduced motion, narrow window')
  const fallback = await browser.newPage({ viewport: { width: 1000, height: 800 } })
  fallback.on('pageerror', e => errors.push(String(e)))
  await fallback.addInitScript(() => {
    const get = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function(type, ...args) { return type.startsWith('webgl') ? null : get.call(this, type, ...args) }
  })
  await fallback.goto(pathToFileURL(resolve(html)).href)
  await fallback.waitForFunction(() => window.particlePreview?.snapshot().ready)
  assert.equal(await fallback.evaluate(() => window.particlePreview.snapshot().mode), 'Canvas 2D')
  await fallback.locator('#occupancy').focus()
  await fallback.keyboard.press('Home'); await fallback.keyboard.press('PageUp')
  await fallback.waitForFunction(() => Math.abs(window.particlePreview.snapshot().progress-.1)<.001)
  await fallback.screenshot({ path: join(resolve(output), 'fallback-perimeter-10.png') })
  await fallback.locator('[data-progress="100"]').click()
  await fallback.waitForFunction(() => window.particlePreview.snapshot().progress > .995)
  await fallback.screenshot({ path: join(resolve(output), 'fallback.png') })
  await fallback.close()
  assert.deepEqual(errors, [])
  assert.deepEqual(requests, [], 'single file makes no network requests')
  await writeFile(join(resolve(output), 'verification.json'), JSON.stringify({ samples, errors, requests }, null, 2))
  console.log('PASS WebGL unavailable fallback; no JS errors or network requests')
} finally { await browser.close() }
